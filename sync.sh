    "# Upstream: https://raw.githubusercontent.com/Johnshall/Shadowrocket-ADBlock-Rules-Forever/release/sr_top500_banlist_ad.conf\n"
    "# Local: shadowrocket-sync/{host,ai,apple}.override.conf\n"
    "# Generated by sync.sh — do not hand-edit\n\n"
)

remote = re.sub(
    r"^dns-server = .*$",
    "dns-server = 8.8.8.8, 1.1.1.1, 223.5.5.5",
    remote,
    count=1,
    flags=re.M,
)

# 扩展 skip-proxy：保留上游原有项，追加 Apple 相关
def patch_skip_proxy(text: str, extra: str) -> str:
    if not extra:
        return text
    m = re.search(r"^skip-proxy\s*=\s*(.*)$", text, flags=re.M)
    if not m:
        return text
    existing = [x.strip() for x in m.group(1).split(",") if x.strip()]
    for item in [x.strip() for x in extra.split(",") if x.strip()]:
        if item not in existing:
            existing.append(item)
    new_line = "skip-proxy = " + ", ".join(existing)
    return text[: m.start()] + new_line + text[m.end() :]

remote = patch_skip_proxy(remote, apple_skip)

# 规则优先级：Apple 直连 > AI Proxy > 上游
apple_block = "# ---- local Apple/App Store DIRECT (highest priority) ----\n" + "\n".join(apple_lines) + "\n\n"
ai_block = "# ---- local AI overrides ----\n" + "\n".join(ai_lines) + "\n\n"
if "[Rule]\n" not in remote:
    raise SystemExit("no [Rule]")
remote = remote.replace("[Rule]\n", "[Rule]\n" + apple_block + ai_block, 1)

# 上游把部分 Apple CDN 写成了 Proxy：整段改成 direct，避免只靠 DOMAIN 漏匹配
remote = re.sub(
    r"(# 苹果域名及其 CDN 代理\n)(.*?)(?=\n# |\n\[)",
    lambda m: m.group(1).replace("代理", "直连(local override)")
    + re.sub(r",Proxy\s*$", ",direct", m.group(2), flags=re.M),
    remote,
    count=1,
    flags=re.S,
)

marker = "[URL Rewrite]"
host_block = "[Host]\n" + "\n".join(host_lines) + "\n"
if marker in remote:
    head, tail = remote.split(marker, 1)
    if "[Host]" in head:
        idx = head.rfind("[Host]")
        before, after = head[:idx], head[idx:]
        lines = after.splitlines(True)
        merged_host = lines[0] + "\n".join(host_lines) + "\n" + "".join(lines[1:])
        body = before + merged_host + marker + tail
    else:
        body = head.rstrip() + "\n\n" + host_block + "\n" + marker + tail
else:
    body = remote.rstrip() + "\n\n" + host_block + "\n"

Path(conf_out).write_text(header + body, encoding="utf-8")

# ---- Clash / Mihomo YAML ----
def sr_to_clash(line: str):
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    # USER-AGENT 仅 Shadowrocket；Clash 跳过
    if line.upper().startswith("USER-AGENT"):
        return None
    parts = [p.strip() for p in line.split(",")]
    if len(parts) < 3:
        return None
    kind, value, policy = parts[0], parts[1], parts[2]
    pol = {
        "Proxy": "PROXY",
        "PROXY": "PROXY",
        "Reject": "REJECT",
        "REJECT": "REJECT",
        "direct": "DIRECT",
        "DIRECT": "DIRECT",
    }.get(policy)
    if not pol:
        return None
    if kind == "DOMAIN-SUFFIX":
        return f"  - DOMAIN-SUFFIX,{value},{pol}"
    if kind == "DOMAIN-KEYWORD":
        return f"  - DOMAIN-KEYWORD,{value},{pol}"
    if kind == "DOMAIN":
        return f"  - DOMAIN,{value},{pol}"
    if kind == "IP-CIDR":
        no_resolve = ",no-resolve" if len(parts) < 4 else ""
        return f"  - IP-CIDR,{value},{pol}{no_resolve}"
    return None

clash_apple = [x for x in (sr_to_clash(ln) for ln in apple_lines) if x]
clash_ai = [x for x in (sr_to_clash(ln) for ln in ai_lines) if x]

ns_policy_lines = []
for hl in host_lines:
    m = re.match(r"^\*?\.?([^=]+)=\s*server:([0-9.]+):(\d+)\s*$", hl.replace(" ", ""))
    if not m:
        m = re.match(r"^\*\.?([\w.-]+)\s*=\s*server:([0-9.]+):(\d+)\s*$", hl)
    if m:
        domain, ip, port = m.group(1), m.group(2), m.group(3)
        domain = domain.lstrip(".")
        ns_policy_lines.append(f"    '+.{domain}': ['{ip}:{port}']")

if not ns_policy_lines:
    ns_policy_lines = ["    '+.bestvmr.com': ['47.110.75.65:8053']"]

stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

if sub_url:
    provider_block = f"""proxy-providers:
  subscription:
    type: http
    url: "{sub_url}"
    path: ./providers/subscription.yaml
    interval: 86400
    override:
      additional-prefix: "[sub] "
    health-check:
      enable: true
      url: https://www.gstatic.com/generate_204
      interval: 600

proxy-groups:
  - name: PROXY
    type: select
    use:
      - subscription
    proxies:
      - DIRECT
"""
else:
    provider_block = """# 未配置节点订阅：请编辑 shadowrocket-sync/subscription.url 后重新 sync
# 或在 Clash 客户端里单独添加订阅，并把策略组名设为 PROXY
proxies: []

proxy-groups:
  - name: PROXY
    type: select
    proxies:
      - DIRECT
"""

yaml_text = f"""# Clash / Mihomo profile

rules:
  # ---- local Apple / App Store DIRECT (highest priority, permanent) ----
{chr(10).join(clash_apple)}
  # ---- local AI / Google overrides ----
{chr(10).join(clash_ai)}
  - RULE-SET,lancidr,DIRECT,no-resolve

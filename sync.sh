log "start sync from $SOURCE_URL"

curl -fsSL --retry 3 --retry-delay 2 --connect-timeout 20 --max-time 180 \
  -A "Mozilla/5.0" -o "$TMP_REMOTE" "$SOURCE_URL"
[[ -s "$TMP_REMOTE" ]] || { log "ERROR: empty remote"; exit 1; }
grep -q '^\[Rule\]' "$TMP_REMOTE" || { log "ERROR: missing [Rule]"; exit 1; }
[[ -f "$HOST_FILE" ]] || { log "ERROR: missing $HOST_FILE"; exit 1; }
[[ -f "$AI_FILE" ]] || { log "ERROR: missing $AI_FILE"; exit 1; }
[[ -f "$APPLE_FILE" ]] || { log "ERROR: missing $APPLE_FILE"; exit 1; }

HOST_LINES="$(grep -v '^#' "$HOST_FILE" | sed '/^[[:space:]]*$/d;1{/^\[Host\]$/d;}')"
AI_LINES="$(grep -v '^#' "$AI_FILE" | sed '/^[[:space:]]*$/d')"
APPLE_LINES="$(grep -v '^#' "$APPLE_FILE" | sed '/^[[:space:]]*$/d')"
SUB_URL=""
if [[ -f "$SUB_FILE" ]]; then
  SUB_URL="$(grep -v '^#' "$SUB_FILE" | sed '/^[[:space:]]*$/d' | head -1 | tr -d '[:space:]')"

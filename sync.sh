python3 - "$TMP_REMOTE" "$TMP_OUT" "$OUT_YAML" "$HOST_LINES" "$AI_LINES" "$APPLE_LINES" "$SUB_URL" "$APPLE_SKIP_EXTRA" <<'PY'
import sys, re
from pathlib import Path
from datetime import datetime, timezone

remote_path, conf_out, yaml_out = sys.argv[1], sys.argv[2], sys.argv[3]
host_lines = [ln for ln in sys.argv[4].splitlines() if ln.strip()]

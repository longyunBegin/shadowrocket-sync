#!/bin/zsh
set -euo pipefail

SCRIPT_DIR="${0:A:h}"
cd "$SCRIPT_DIR"

if ! gh auth status >/dev/null 2>&1; then
  print -r -- "未登录 GitHub。请先在【本机 Terminal.app】执行："
  print -r -- ""
  print -r -- "  gh auth login -h github.com -p https -w -s gist"
  print -r -- ""
  print -r -- "登录完成后再运行："
  print -r -- "  ~/Downloads/shadowrocket-sync/setup-gist.sh"
  exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
  print -r -- "缺少 jq，正在用 brew 安装..."
  brew install jq
fi

./sync.sh

LOGIN="$(gh api user -q .login)"
DESC="Shadowrocket flyint (Johnshall + local Host) auto-synced"
OUT_CONF="$SCRIPT_DIR/out/flyint.conf"

# Create private gist via API for stable filename flyint.conf
GIST_JSON="$(jq -n --rawfile content "$OUT_CONF" \
  --arg desc "$DESC" \
  '{description:$desc, public:false, files:{"flyint.conf":{content:$content}}}')"
ID="$(print -r -- "$GIST_JSON" | gh api -X POST gists --input - -q .id)"

if [[ -z "$ID" ]]; then
  print -r -- "ERROR: failed to create gist"
  exit 1
fi

RAW_URL="https://gist.githubusercontent.com/${LOGIN}/${ID}/raw/flyint.conf"
RAW_URL_YAML="https://gist.githubusercontent.com/${LOGIN}/${ID}/raw/flyint.yaml"

cat > "$SCRIPT_DIR/config.env" <<ENV
# generated by setup-gist.sh — do not commit secrets elsewhere if any
GIST_ID=$ID
RAW_URL=$RAW_URL
RAW_URL_YAML=$RAW_URL_YAML
ENV

print -r -- ""
print -r -- "✅ 私有 Gist 已创建"
print -r -- ""
print -r -- "所有手机 Shadowrocket → 配置 → + → 类型选【远程文件】→ URL 填："
print -r -- ""
print -r -- "  $RAW_URL"
print -r -- ""
print -r -- "打开自动更新（建议 24 小时）。Mac 每天 09:10 会合并 override 并推送到这个地址。"
print -r -- ""
print -r -- "启用 Mac 定时任务（若还没装过，在 Terminal 执行一次）："
print -r -- "  launchctl bootstrap gui/\$(id -u) ~/Library/LaunchAgents/com.longyun.shadowrocket-sync.plist"
